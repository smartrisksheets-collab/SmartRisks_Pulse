def main() -> int:
    if len(sys.argv) != 2:
        print("Usage: python apply_brand_vars.py <path to index.css>")
        return 2
    path = sys.argv[1]
    with open(path, encoding="utf-8") as fh:
        css = fh.read()

    failed = [(name, css.count(find), count) for name, find, _, count in R if css.count(find) != count]
    if failed:
        print("No changes written. These find strings did not match the expected count:")
        for name, found, want in failed:
            print(f"  - {name}: found {found}, expected {want}")
        return 1

    for _, find, repl, _ in R:
        css = css.replace(find, repl)

    shutil.copyfile(path, path + ".bak")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(css)
    print(f"Applied {len(R)} replacements. Backup saved as {path}.bak")
    return 0


if __name__ == "__main__":
    sys.exit(main())